/**
 * 检索：**多词先按 AND 收敛**（每个词都要在某处出现），命中的再按权重排序；
 * 若一个"全词命中"的都没有（多半是打错字），才退化成"部分命中"并在结果里标 `full:false`
 * —— 宁可少给，也不要把不相干的条目塞给人。
 * 权重：`symptom` 5 > `tags` 3 > `ask` 2 > `steps`/`avoid` 1；传 `tag` 时该标签再加 4。
 */
export function kbSearch(query, opts) {
  const o = opts || {};
  const words = String(query == null ? '' : query).trim().toLowerCase().split(/\s+/).filter(Boolean);
  const scored = KB_ENTRIES.map((e) => {
    const hay = {
      symptom: e.symptom.toLowerCase(),
      tags: (e.tags || []).join(' ').toLowerCase(),
      ask: (e.ask || []).join(' ').toLowerCase(),
      steps: (e.steps || []).join(' ').toLowerCase(),
      other: [e.avoid || '', e.id].join(' ').toLowerCase(),
    };
    const all = Object.values(hay).join(' ');
    let score = 0;
    for (const w of words) {
      if (hay.symptom.includes(w)) score += 5;
      if (hay.tags.includes(w)) score += 3;
      if (hay.ask.includes(w)) score += 2;
      if (hay.steps.includes(w)) score += 1;
      if (hay.other.includes(w)) score += 1;
    }
    if (o.tag && (e.tags || []).includes(String(o.tag))) score += 4;
    const full = words.every((w) => all.includes(w));
    return { entry: e, score, full };
  });
  const anyFull = scored.some((x) => x.full && x.score > 0);
  const hit = words.length || o.tag
    ? scored.filter((x) => x.score > 0 && (anyFull ? x.full : true))
    : scored;
  return hit.sort((a, b) => b.score - a.score || a.entry.id.localeCompare(b.entry.id))
    .slice(0, o.limit && o.limit > 0 ? o.limit : 5);
}

/** 目录（`op=qa` 不给 q 时回这个）：症状 + 标签，方便模型挑。 */
export function kbCatalog() {
  return KB_ENTRIES.map((e) => ({ id: e.id, symptom: e.symptom, tags: e.tags }));
}

/** 按 id 取一条（给"我已经知道是哪条"的调用）。 */
export function kbEntry(id) {
  return KB_ENTRIES.find((e) => e.id === String(id)) || null;
}

/** 出处：把 `src` id 数组翻成 {title,url,kind}。 */
export function kbSources(ids) {
  return (ids || []).map((id) => Object.assign({ id }, KB_SOURCES[id] || { title: id, url: null, kind: '未登记' }));
}
